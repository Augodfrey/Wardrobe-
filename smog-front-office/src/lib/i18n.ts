export type MsgKey = keyof typeof en;
const dict: Record<Lang, typeof en> = { en, es };

export function t(lang: Lang, key: MsgKey, vars: Record<string, string | number> = {}): string {
  return dict[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export const allKeysTranslated = () => (Object.keys(en) as MsgKey[]).every((k) => !!es[k]);
